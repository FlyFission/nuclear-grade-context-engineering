"""Two-party integrity for load-bearing claims.

Ports the segregation-of-duties idea -- the party that produces a result cannot
also be the party that accepts it -- to the packet's independence principle: a
claim marked ``pass`` should name a verifier who is neither the author of its
evidence nor the change actor.

The check reads two declarations, whichever the packet carries:

1. The evidence-custody record (``## Evidence custody and coupling``), which the
   validator already parses. A custody row counts as a second party when its
   ``Verified / witnessed by`` differs from both ``Generated by`` and the
   ``Change actor`` *and* its coupling profile is classified as something other
   than ``self-check``.
2. A lightweight ``## Claim authorship`` table, for packets that do not carry a
   full custody record::

       ## Claim authorship
       | Claim ID | Evidence author | Verified by |
       |----------|-----------------|-------------|
       | REQ-001  | agent:claude    | ben         |

Enforcement is graded:

- ``required=True`` (``ng validate --two-party``): every ``pass`` claim must have
  a second party from either source, or validation fails.
- ``required=False`` (default): legacy packets stay valid, but a packet that
  *opts in* by declaring a ``## Claim authorship`` table is held to it, because a
  declared authorship record that names the author as its own verifier is a
  contradiction, not a missing disclosure.

What this does not do: it compares declared identity strings. It cannot detect
two names for one actor, two agent instances of one model family sharing an
orchestrator, or a verifier who rubber-stamped. Those couplings are what the
five-axis profile in ``docs/02-operating-system/actor-evidence-independence.md``
records, and the merge-level half of two-party integrity still belongs to
branch protection ("require review from someone other than the author") plus a
real CODEOWNERS file.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import NamedTuple

# Aligned with ng_validate.RECORD_ID_PATTERN so ids such as `C-004a` are seen;
# a short free-text description may follow the id after whitespace.
_CLAIM_ID = re.compile(r"^(?P<id>[A-Z][A-Z0-9]*-?[0-9][A-Za-z0-9._-]*)(?:\s|$)")
_STATUSES = {"pass", "fail", "gap", "deferred", "not applicable", "planned"}
# Cells that declare the absence of a verifier rather than naming one.
_EMPTY_PARTY = {
    "",
    "-",
    "--",
    "—",
    "none",
    "n/a",
    "na",
    "tbd",
    "pending",
    "not applicable",
}
_EMPTY_PARTY_PREFIXES = ("no separate", "no independent", "none ", "none;", "none,", "pending")
# H2 sections whose tables are not the claim-to-evidence table.
_NON_CLAIM_SECTIONS = ("claim authorship", "evidence custody")


class ClaimParty(NamedTuple):
    """One declared author/verifier pairing that bears on a claim."""

    source: str
    author: str
    verifier: str
    change_actor: str = ""
    # Empty for the authorship table (no classification is declared there).
    classification: str = ""


def _claim_id(cell: str) -> str | None:
    """Return the leading claim id, allowing a short description after it."""
    match = _CLAIM_ID.match(cell.strip())
    return match.group("id") if match else None


def _norm(value: str) -> str:
    return " ".join(value.casefold().replace("*", "").replace("`", "").split())


def _is_empty_party(value: str) -> bool:
    norm = _norm(value)
    return norm in _EMPTY_PARTY or norm.startswith(_EMPTY_PARTY_PREFIXES)


def _h2_title(line: str) -> str | None:
    stripped = line.strip()
    if stripped.startswith("## ") and not stripped.startswith("### "):
        return stripped[3:].strip().casefold()
    return None


def parse_claim_status(verification_text: str) -> dict[str, str]:
    """Return ``{claim_id: status}`` from the claim-to-evidence table(s).

    Rows inside the custody and authorship sections are skipped so an evidence
    or authorship row can never be mistaken for a claim.
    """
    out: dict[str, str] = {}
    skip = False
    for line in verification_text.splitlines():
        title = _h2_title(line)
        if title is not None:
            skip = title.startswith(_NON_CLAIM_SECTIONS)
            continue
        if skip or "|" not in line:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 2 or (claim_id := _claim_id(cells[0])) is None:
            continue
        status = next((c.lower() for c in cells[1:] if c.lower() in _STATUSES), None)
        if status is not None:
            # When a base row and a qualified row share a normalized id (e.g.
            # `REQ-001` and `REQ-001 (live install)`), keep the load-bearing
            # `pass` so a weaker later row cannot silently drop the independence
            # check this module exists to enforce.
            if claim_id not in out or status == "pass":
                out[claim_id] = status
    return out


def parse_authorship(verification_text: str) -> dict[str, tuple[str, str]]:
    """Return ``{claim_id: (evidence_author, verified_by)}`` from the authorship table.

    Only rows under a '## Claim authorship' heading are read, so this never
    collides with the main claim-to-evidence table.
    """
    out: dict[str, tuple[str, str]] = {}
    in_section = False
    for line in verification_text.splitlines():
        title = _h2_title(line)
        if title is not None:
            in_section = title.startswith("claim authorship")
            continue
        if not in_section or "|" not in line:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or (claim_id := _claim_id(cells[0])) is None:
            continue
        out[claim_id] = (cells[1], cells[2])
    return out


def _excluded_identities(party: ClaimParty) -> set[str]:
    """Identities that cannot serve as this party's second party.

    For the authorship table the evidence author is, by construction, the side
    being checked. For a custody row the reference is the change actor: an
    independent reproducer legitimately both generates and witnesses their own
    re-run, and the custody lint already forces actor-controlled evidence paths
    to be classified as self-check.
    """
    if party.source.startswith("custody"):
        return {_norm(party.change_actor)} - {""}
    return {_norm(party.author), _norm(party.change_actor)} - {""}


def _is_second_party(party: ClaimParty) -> bool:
    if _is_empty_party(party.verifier):
        return False
    if _norm(party.verifier) in _excluded_identities(party):
        return False
    # A custody row's own classification is the stronger declaration: a row the
    # author classified as self-check is not a second party, whatever it names.
    return _norm(party.classification) != "self-check"


def _why_not(cid: str, parties: list[ClaimParty]) -> str:
    named = [p for p in parties if not _is_empty_party(p.verifier)]
    if not named:
        return (
            f"verification.md: claim {cid} is 'pass' but every declared verifier is "
            "empty; a load-bearing claim needs a named second party."
        )
    for party in named:
        if _norm(party.verifier) in _excluded_identities(party):
            return (
                f"verification.md: claim {cid} verified by its own evidence author or "
                f"change actor ('{party.verifier}', {party.source}); an independent "
                "second party is required."
            )
    return (
        f"verification.md: claim {cid} is 'pass' on self-check evidence only; record "
        "an independent second party, or narrow the status and carry the coupling "
        "as residual risk in ship.md."
    )


def check_two_party(
    packet: str | Path,
    messages: list[str],
    *,
    custody_parties: dict[str, list[ClaimParty]] | None = None,
    required: bool = True,
) -> None:
    """Append a message when a ``pass`` claim lacks an independent second party.

    ``custody_parties`` is the ``{claim_id: [ClaimParty]}`` map the validator
    builds from the custody record. ``required`` selects strict enforcement;
    see the module docstring for the graded behavior.
    """
    vfile = Path(packet) / "verification.md"
    if not vfile.exists():
        return
    text = vfile.read_text(encoding="utf-8")

    statuses = parse_claim_status(text)
    if not statuses and required:
        # Fail closed: strict mode with nothing parseable is not a clean result.
        messages.append(
            "verification.md: no claim-to-evidence rows with Claim IDs and a status "
            "were found; two-party verification has nothing to check (add a "
            "claim-to-evidence table, as in templates/standard/verification.md)."
        )
        return
    verified = {cid for cid, st in statuses.items() if st == "pass"}
    if not verified:
        return

    authorship = parse_authorship(text)
    custody = custody_parties or {}
    enforce = required or bool(authorship)
    if not enforce:
        return

    if not authorship and not custody:
        messages.append(
            "verification.md: claims are marked 'pass' but neither a 'Claim authorship' "
            "table nor an evidence-custody record says who drafted versus verified "
            "each; two-party integrity cannot be confirmed (add one, or enforce at "
            "merge via branch protection)."
        )
        return

    for cid in sorted(verified):
        parties = list(custody.get(cid, []))
        if cid in authorship:
            author, verifier = authorship[cid]
            parties.append(ClaimParty("claim authorship", author, verifier))
        if not parties:
            messages.append(
                f"verification.md: claim {cid} is 'pass' but has no authorship or "
                "custody row; cannot confirm an independent verifier."
            )
            continue
        if any(_is_second_party(p) for p in parties):
            continue
        messages.append(_why_not(cid, parties))
